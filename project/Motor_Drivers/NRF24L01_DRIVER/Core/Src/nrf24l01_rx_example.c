/**
 * @brief Basic receiver initialization and data reading
 */
void NRF24L01_RX_Basic_Example(void)
{
    // Initialize NRF24L01 receiver
    NRF24L01_RX_Init();

    // Wait for pairing with remote (timeout 10 seconds)
    if (!NRF24L01_RX_WaitForPairing()) {
        printf("Pairing failed! Check remote controller.\n");
        return;
    }
    printf("Paired successfully!\n");

    while (1) {
        // Check and read data
        if (NRF24L01_RX_ReadData()) {
            // Get parsed data
            RemoteControlData_t *rc_data = NRF24L01_RX_GetData();

            // Use the data (joystick values: 128=center, <128=left/forward, >128=right/backward)
            uint8_t right_x = rc_data->right_joystick_x;
            uint8_t right_y = rc_data->right_joystick_y;
            uint8_t left_x = rc_data->left_joystick_x;
            uint8_t left_y = rc_data->left_joystick_y;
            uint8_t button = rc_data->button_state;

            // Example: Print to debug
            printf("RX:%d RY:%d LX:%d LY:%d BTN:0x%02X\n",
                   right_x, right_y, left_x, left_y, button);
        }

        HAL_Delay(10); // 100Hz check rate
    }
}

