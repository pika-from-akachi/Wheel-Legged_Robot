/* ============================================================================
 *                          EXAMPLE 6: STATUS MONITORING
 * ============================================================================ */

/**
 * @brief Monitor receiver status
 */
void MonitorReceiverStatus(void)
{
    static uint32_t last_print_time = 0;

    // Print status every 1 second
    if (HAL_GetTick() - last_print_time >= 1000) {
        last_print_time = HAL_GetTick();

        if (NRF24L01_RX_IsOnline()) {
            RemoteControlData_t *rc = NRF24L01_RX_GetData();
            printf("Remote Online - RX:%d RY:%d LX:%d LY:%d BTN:0x%02X\n",
                   rc->right_joystick_x, rc->right_joystick_y,
                   rc->left_joystick_x, rc->left_joystick_y,
                   rc->button_state);
        } else {
            printf("Remote Offline!\n");
        }
    }
}

